// Connects Java ForgotPasswordActivity to Jetpack Compose ForgotPasswordScreen
// Simplified flow: Email only → Firebase sends reset link
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

/**
 * State holder for forgot password screen.
 * Simplified for Firebase Auth password reset link flow.
 */
class ForgotPasswordStateHolder {
    
    var email by mutableStateOf("")
    var isLoading by mutableStateOf(false)
    var emailSent by mutableStateOf(false)
    var error: String? by mutableStateOf(null)
    
    /**
     * Clears the current error message.
     */
    fun clearError() {
        error = null
    }
    
    /**
     * Resets the state to default values.
     */
    fun reset() {
        email = ""
        emailSent = false
        error = null
        isLoading = false
    }
    
    /**
     * Validates the current email address.
     */
    fun isEmailValid(): Boolean = email.isNotBlank() && email.contains("@") && email.contains(".")
    
    // Note: getEmail(), setEmail(), isLoading(), setLoading(), etc. 
    // are automatically generated by Kotlin for the properties above 
    // and are accessible from Java.
}

/**
 * Sets up the Compose UI for ForgotPasswordActivity.
 */
fun ForgotPasswordActivity.setupComposeUI(stateHolder: ForgotPasswordStateHolder) {
    setContent {
        SafarTheme(darkTheme = true) {
            ForgotPasswordScreen(
                email = stateHolder.email,
                isLoading = stateHolder.isLoading,
                emailSent = stateHolder.emailSent,
                error = stateHolder.error,
                onEmailChanged = { stateHolder.email = it },
                onRequestReset = { 
                    if (stateHolder.isEmailValid()) {
                        handleRequestReset(stateHolder.email) 
                    }
                },
                onResend = { handleResendCode() },
                onBack = { handleBack() }
            )
        }
    }
}
